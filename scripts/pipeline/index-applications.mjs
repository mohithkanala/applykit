#!/usr/bin/env node
// index-applications.mjs
// Disk-scanning indexer for the applications/ tree. Parallel-chat-safe:
// each chat just drops a folder under applications/pending/{slug}/ with its
// artifacts; running this regenerates applications/INDEX.md from folder truth,
// so nothing gets lost across concurrent sessions. Zero LLM cost.
//
// Usage:  node scripts/pipeline/index-applications.mjs
// Writes: applications/INDEX.md  (+ prints a summary to stdout)

import { readdirSync, statSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const APPS = join(ROOT, 'applications');
const PENDING = join(APPS, 'pending');
const APPLIED = join(APPS, 'applied');

const isDir = (p) => { try { return statSync(p).isDirectory(); } catch { return false; } };
const listDirs = (p) => existsSync(p) ? readdirSync(p).filter((n) => isDir(join(p, n))) : [];

// newest mtime among a folder's own files (non-recursive is enough for activity)
function newestMtime(dir) {
  let newest = 0;
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const fp = join(d, n);
      const s = statSync(fp);
      if (s.isDirectory()) { if (n !== 'versions') walk(fp); }
      else newest = Math.max(newest, s.mtimeMs);
    }
  };
  try { walk(dir); } catch {}
  return newest;
}

function fileList(dir) {
  const out = [];
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const fp = join(d, n);
      if (isDir(fp)) { if (n !== 'versions') walk(fp); }
      else out.push(n);
    }
  };
  try { walk(dir); } catch {}
  return out;
}

function readJson(p) { try { return JSON.parse(readFileSync(p, 'utf8')); } catch { return null; } }

function scanJob(baseDir, slug) {
  const dir = join(baseDir, slug);
  const files = fileList(dir);
  const has = (re) => files.some((f) => re.test(f));

  const manifest = readJson(join(dir, 'manifest.json'));
  const verdict = readJson(join(dir, 'validator-verdict.json'));

  const jd = has(/^JD\.md$/i);
  const resume = has(/Resume\.pdf$/i);
  const cover = has(/Cover_Letter\.(pdf|docx|md)$/i);
  const outreach = has(/outreach/i);        // outreach.md, outreach-*.md, *-outreach.md
  const form = has(/application-form\.md$/i);

  const vw = verdict?.verdict_for_workflow || null;   // SHIP | REFINE
  const score = verdict?.score ?? null;
  const fit = verdict?.overall_fit || null;

  const company = manifest?.meta?.company || null;
  const role = manifest?.meta?.role || null;
  const date = manifest?.meta?.date || null;

  // readiness classification
  let status;
  if (!resume) status = jd ? '🟠 JD-only' : '⚪ empty';
  else if (vw === 'SHIP') status = '🟢 ready';
  else if (vw === 'REFINE') status = '🔴 refine';
  else status = '🟡 unvalidated';

  return { slug, dir, company, role, date, jd, resume, cover, outreach, form,
           vw, score, fit, status, mtime: newestMtime(dir) };
}

const yn = (b) => (b ? '✅' : '·');
const fmtDate = (ms) => new Date(ms).toISOString().slice(0, 10);

// ---- scan pending ----
const pending = listDirs(PENDING)
  .filter((s) => !s.startsWith('_'))
  .map((s) => scanJob(PENDING, s))
  .sort((a, b) => b.mtime - a.mtime);

// loose top-level outreach/misc .md files in pending
const looseFiles = existsSync(PENDING)
  ? readdirSync(PENDING).filter((n) => n.endsWith('.md') && !isDir(join(PENDING, n)))
  : [];

// ---- scan applied (mixed tree: date/slug, company/slug, or direct company leaf) ----
// A "leaf" = a folder whose OWN files include a resume or JD.md. Recurse to find them.
const ownFiles = (d) => { try { return readdirSync(d).filter((n) => !isDir(join(d, n))); } catch { return []; } };
const isLeaf = (d) => ownFiles(d).some((f) => /Resume\.pdf$/i.test(f) || /^JD\.md$/i.test(f));
const appliedLeaves = [];
const findLeaves = (d, rel) => {
  if (isLeaf(d)) { appliedLeaves.push({ label: rel, mtime: newestMtime(d) }); return; }
  for (const sub of listDirs(d)) findLeaves(join(d, sub), rel ? `${rel}/${sub}` : sub);
};
for (const top of listDirs(APPLIED)) findLeaves(join(APPLIED, top), top);
appliedLeaves.sort((a, b) => b.mtime - a.mtime);

// ---- counts ----
const c = { ready: 0, refine: 0, unval: 0, jdonly: 0, empty: 0 };
for (const p of pending) {
  if (p.status.includes('ready')) c.ready++;
  else if (p.status.includes('refine')) c.refine++;
  else if (p.status.includes('unvalidated')) c.unval++;
  else if (p.status.includes('JD-only')) c.jdonly++;
  else c.empty++;
}
const missingOutreach = pending.filter((p) => p.resume && !p.outreach).length;

// ---- render ----
const now = new Date().toISOString().replace('T', ' ').slice(0, 16);
let md = `# Applications Index\n\n`;
md += `_Auto-generated by \`scripts/pipeline/index-applications.mjs\` — do not edit by hand. Regenerate after any build._\n\n`;
md += `**Generated:** ${now}\n\n`;
md += `## Summary\n\n`;
md += `- **Pending:** ${pending.length}  →  🟢 ready ${c.ready} · 🔴 refine ${c.refine} · 🟡 unvalidated ${c.unval} · 🟠 JD-only ${c.jdonly} · ⚪ empty ${c.empty}\n`;
md += `- **Ready but no outreach drafted:** ${missingOutreach}\n`;
md += `- **Applied:** ${appliedLeaves.length}\n\n`;
md += `Status legend: 🟢 resume + validator SHIP · 🔴 validator REFINE (fix before send) · 🟡 resume built, not validated · 🟠 JD captured only · ⚪ empty.\n\n`;

md += `## Pending (${pending.length}) — newest first\n\n`;
md += `| Status | Slug | Company / Role | Res | CL | Out | Form | Val | Updated |\n`;
md += `|---|---|---|:-:|:-:|:-:|:-:|:--|:--|\n`;
for (const p of pending) {
  const cr = p.company ? `${p.company}${p.role ? ' — ' + p.role : ''}` : '';
  const val = p.vw ? `${p.vw}${p.score != null ? ' ' + p.score : ''}` : '';
  md += `| ${p.status} | ${p.slug} | ${cr} | ${yn(p.resume)} | ${yn(p.cover)} | ${yn(p.outreach)} | ${yn(p.form)} | ${val} | ${fmtDate(p.mtime)} |\n`;
}
md += `\n`;

if (looseFiles.length) {
  md += `### Loose files in pending/ (not a job folder)\n\n`;
  for (const f of looseFiles) md += `- \`${f}\`\n`;
  md += `\n`;
}

md += `## Applied (${appliedLeaves.length}) — newest first\n\n`;
for (const a of appliedLeaves) md += `- ${fmtDate(a.mtime)} — \`${a.label}\`\n`;
md += `\n`;

writeFileSync(join(APPS, 'INDEX.md'), md, 'utf8');

// stdout summary
console.log(`Applications index refreshed → applications/INDEX.md`);
console.log(`  Pending ${pending.length}: ready ${c.ready}, refine ${c.refine}, unvalidated ${c.unval}, JD-only ${c.jdonly}, empty ${c.empty}`);
console.log(`  Ready but no outreach: ${missingOutreach}`);
console.log(`  Applied: ${appliedLeaves.length}`);
if (c.refine) console.log(`  ⚠ REFINE (fix before send): ${pending.filter(p=>p.status.includes('refine')).map(p=>p.slug).join(', ')}`);
